def w(d, rel, text):
    path = os.path.join(d, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text if text.endswith("\n") else text + "\n")


def answer(card):
    r = random.Random(card["id"])
    inc = card["income"] / 8000000.0
    p = BUY.get(card["behaviour"], .3) + (inc - 0.9) * 0.08
    buys = r.random() < p
    pool = YES if buys else NO
    code = r.choice(sorted(pool))
    tc = round(r.uniform(8000, 13000) * (0.85 + min(inc, 3) * 0.15), -2)
    ch = round(tc + r.uniform(3000, 6000), -2)
    ex = round(ch + r.uniform(4000, 8000), -2)
    te = round(ex + r.uniform(3000, 7000), -2)
    return {"id": card["id"], "buys": buys, "purchases_first_month": r.randint(2, 14) if buys else 0,
            "reason_code": code, "reason": r.choice(pool[code]), "objection": card["objection"],
            "would_change_my_mind": "" if buys else r.choice(FLIP),
            "price_too_cheap": tc, "price_cheap": ch, "price_expensive": ex, "price_too_expensive": te}


